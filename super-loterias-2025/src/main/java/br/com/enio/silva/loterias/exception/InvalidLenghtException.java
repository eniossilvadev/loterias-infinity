package br.com.enio.silva.loterias.exception;

public class InvalidLenghtException extends Exception {

	/**
	 *
	 */
	private static final long serialVersionUID = 990262882468283624L;

	public InvalidLenghtException() {
		super();
	}

	public InvalidLenghtException(String arg0) {
		super(arg0);
	}

	public InvalidLenghtException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public InvalidLenghtException(String arg0, Throwable arg1, boolean arg2, boolean arg3) {
		super(arg0, arg1, arg2, arg3);
	}

	public InvalidLenghtException(Throwable arg0) {
		super(arg0);
	}

}
